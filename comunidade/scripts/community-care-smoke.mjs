import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
const base = process.env.ICABV_TEST_URL || 'http://localhost:5173';
const browser = await chromium.launch({ headless: true });
try {
 const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
 const page = await context.newPage();
 const errors = [];
 let remote = 0;
 page.on('pageerror', e => errors.push(e.message));
 await context.route('**/*.supabase.co/**', async route => { remote++; await route.abort(); });
 await page.goto(`${base}/demo?perfil=gestor&tab=food-drive`);
 await page.getByRole('heading', { name: 'Cestas básicas', exact: true }).waitFor();
 const rice = page.locator('article.care-item').filter({ has: page.getByRole('heading', { name: 'Arroz', exact: true }) });
 await rice.getByLabel('Quantidade de Arroz que vou levar', { exact: true }).fill('3');
 await rice.getByRole('button', { name: 'Quero contribuir', exact: true }).click();
 await rice.getByRole('button', { name: 'Atualizar contribuição', exact: true }).waitFor();
 await rice.getByText('Minha contribuição:', { exact: false }).filter({ hasText: '3' }).waitFor();
 const receipt = page.locator('form.care-receipt').filter({ has: page.getByLabel('Total recebido de Ana Exemplo — Arroz', { exact: true }) });
 await receipt.getByLabel('Total recebido de Ana Exemplo — Arroz', { exact: true }).fill('2');
 await receipt.getByRole('button', { name: 'Confirmar recebimento' }).click();
 await rice.getByLabel('Quantidade de Arroz que vou levar', { exact: true }).waitFor();
 await page.waitForFunction(() => document.querySelector('input[name="amount"]')?.getAttribute('min') === '2');
 assert.equal(await rice.getByLabel('Quantidade de Arroz que vou levar').getAttribute('min'), '2');
 assert.equal(await rice.locator('progress').getAttribute('value'), '3');
 await page.getByRole('button', { name: 'Adicionar item', exact: true }).click();
 await page.getByLabel('Nome do item', { exact: true }).fill('Óleo de soja');
 await page.getByLabel('Unidade / embalagem', { exact: true }).fill('garrafa de 900 ml');
 await page.getByLabel('Quantidade necessária', { exact: true }).fill('12');
 await page.getByRole('button', { name: 'Salvar', exact: true }).click();
 await page.getByRole('heading', { name: 'Óleo de soja', exact: true }).waitFor();
 await page.getByRole('button', { name: 'Editar campanha', exact: true }).click();
 await page.getByLabel('Situação', { exact: true }).selectOption('closed');
 await page.getByRole('button', { name: 'Salvar', exact: true }).click();
 await page.getByText('Campanha encerrada para contribuições', { exact: false }).waitFor();
 assert.equal(await rice.getByRole('button', { name: 'Atualizar contribuição' }).isDisabled(), true);
 mkdirSync('test-results/community-care', { recursive: true });
 await page.screenshot({ path: 'test-results/community-care/campaign-mobile.png', fullPage: true });
 assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
 // Create and select a separate campaign: no copying of previous commitments.
 await page.getByRole('button', { name: 'Nova campanha', exact: true }).click();
 await page.getByLabel('Nome da campanha', { exact: true }).fill('Campanha de teste');
 await page.getByLabel('Local e horário de entrega', { exact: true }).fill('Secretaria aos domingos');
 await page.getByLabel('Prazo de contribuição', { exact: true }).fill('2099-12-31');
 await page.getByRole('button', { name: 'Salvar', exact: true }).click();
 await page.getByLabel('Campanha', { exact: true }).selectOption({ label: 'Campanha de teste · Aberta' });
 await page.getByText('Os itens desta campanha ainda não foram definidos.', { exact: true }).waitFor();
 await page.setViewportSize({ width: 1440, height: 1000 });
 await page.screenshot({ path: 'test-results/community-care/campaign-desktop.png', fullPage: true });
 await page.goto(`${base}/demo?perfil=membro&tab=birthdays`);
 await page.getByRole('heading', { name: 'Aniversariantes da igreja' }).waitFor();
 await page.getByText('Hoje 🎉', { exact: true }).waitFor();
 assert.equal(await page.getByText('1990', { exact: true }).count(), 0);
 await page.screenshot({ path: 'test-results/community-care/birthdays.png', fullPage: true });
 await page.goto(`${base}/demo?perfil=membro&tab=profile`);
 const sharing = page.getByLabel('Compartilhar meu aniversário com a igreja', { exact: true });
 await sharing.uncheck();
 await page.getByRole('button', { name: 'Salvar', exact: true }).click();
 // Navigate inside the same demonstration session, preserving the in-memory setting.
 await page.getByRole('button', { name: 'Voltar ao início', exact: true }).click();
 await page.getByText('Nenhum aniversário compartilhado neste mês.', { exact: true }).waitFor();
 await page.getByRole('button', { name: 'Cestas básicas', exact: false }).first().click();
 await page.getByRole('heading', { name: 'Cestas básicas', exact: true }).waitFor();
 assert.equal(await page.getByRole('button', { name: 'Nova campanha', exact: true }).count(), 0);
 assert.equal(await page.getByRole('heading', { name: 'Conferir entregas', exact: true }).count(), 0);
 assert.equal(remote, 0, 'Demonstração não acessa dados reais');
 assert.deepEqual(errors, []);
 console.log('OK: aniversariantes, destaque de hoje, retirada do compartilhamento, múltiplos itens, compromisso, recebimento parcial, campanha encerrada, nova campanha, gestão restrita e layout móvel.');
 await context.close();
} finally { await browser.close(); }
